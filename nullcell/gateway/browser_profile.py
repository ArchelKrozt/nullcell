"""The dedicated browser profile — §8.

§8 chose an existing browser with a profile of its own, and the choice only
works if the profile is actually isolated. Every preference below exists
against a specific leak, and the table in §8 names them:

================================================  ===========================
``network.proxy.socks_remote_dns = true``         **Critical.** Without it the
                                                  browser resolves ``.null``
                                                  through the ISP's resolver:
                                                  every name you visit leaks,
                                                  and it does not work anyway.
``media.peerconnection.enabled = false``          WebRTC reveals local and real
                                                  IP addresses.
geolocation, telemetry, autofill off              Less fingerprint, fewer traces.
a separate profile                                No cookies, history or
                                                  sessions from the ordinary
                                                  internet.
================================================  ===========================

The local CA goes **only here** (§8), never into the system trust store.
Firefox keeps its trust in an NSS database, so importing needs ``certutil``
from the NSS tools. When it is missing, this module says so and prints the
command rather than failing quietly or, worse, suggesting the system store.
"""

from __future__ import annotations

import logging
import shutil
import subprocess
from pathlib import Path
from typing import Final

__all__ = ["PREFS", "BrowserProfile", "firefox_binary"]

log = logging.getLogger("nullcell.browser")

#: §8's table, as Firefox preferences.
PREFS: Final[dict[str, object]] = {
    # The proxy, and the one preference §8 calls critical.
    "network.proxy.type": 1,
    "network.proxy.socks": "127.0.0.1",
    "network.proxy.socks_port": 9150,
    "network.proxy.socks_version": 5,
    "network.proxy.socks_remote_dns": True,
    "network.proxy.allow_hijacking_localhost": True,
    # WebRTC reveals local and real IPs.
    "media.peerconnection.enabled": False,
    "media.peerconnection.ice.default_address_only": True,
    # Geolocation.
    "geo.enabled": False,
    "geo.provider.use_corelocation": False,
    "permissions.default.geo": 2,
    # Telemetry and phoning home of every kind.
    "toolkit.telemetry.enabled": False,
    "toolkit.telemetry.unified": False,
    "datareporting.healthreport.uploadEnabled": False,
    "datareporting.policy.dataSubmissionEnabled": False,
    "app.shield.optoutstudies.enabled": False,
    "browser.safebrowsing.malware.enabled": False,
    "browser.safebrowsing.phishing.enabled": False,
    "network.captive-portal-service.enabled": False,
    "network.connectivity-service.enabled": False,
    "browser.search.suggest.enabled": False,
    "browser.urlbar.suggest.searches": False,
    # Autofill and saved credentials: fewer traces in a profile that is
    # supposed to know nothing about you.
    "signon.rememberSignons": False,
    "browser.formfill.enable": False,
    "extensions.pocket.enabled": False,
    # DNS over HTTPS would be another resolver seeing the names.
    "network.trr.mode": 5,
    # Our CA is in this profile's store; nothing else should be added to it.
    "security.enterprise_roots.enabled": False,
    # First run noise, so `ncell browse` lands on the page it was asked for.
    "browser.startup.homepage_override.mstone": "ignore",
    "datareporting.policy.firstRunURL": "",
    "browser.aboutwelcome.enabled": False,
}


def firefox_binary() -> Path | None:
    """Find Firefox, or return None."""
    found = shutil.which("firefox")
    if found:
        return Path(found)
    candidates = [
        Path("/Applications/Firefox.app/Contents/MacOS/firefox"),
        Path("/usr/bin/firefox"),
        Path("/snap/bin/firefox"),
        Path(r"C:\Program Files\Mozilla Firefox\firefox.exe"),
    ]
    return next((path for path in candidates if path.exists()), None)


class BrowserProfile:
    """Builds and launches the isolated profile of §8."""

    def __init__(self, directory: Path, *, socks_port: int = 9150) -> None:
        self.directory = directory
        self.socks_port = socks_port

    @property
    def prefs_path(self) -> Path:
        return self.directory / "user.js"

    def prefs(self) -> dict[str, object]:
        return {**PREFS, "network.proxy.socks_port": self.socks_port}

    def write(self) -> Path:
        """Write ``user.js``. Firefox applies it on every start."""
        self.directory.mkdir(parents=True, exist_ok=True)
        lines = [
            "// Generated by ncell. Every line here answers a leak named in §8",
            "// of NULLCELL-ARQUITECTURA.md. Edit the source, not this file:",
            "// Firefox rewrites prefs.js, and user.js is reapplied each start.",
        ]
        for key, value in sorted(self.prefs().items()):
            if isinstance(value, bool):
                rendered = "true" if value else "false"
            elif isinstance(value, int):
                rendered = str(value)
            else:
                rendered = '"' + str(value).replace('"', '\\"') + '"'
            lines.append(f'user_pref("{key}", {rendered});')
        self.prefs_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return self.prefs_path

    # ------------------------------------------------------------------ the CA
    def install_ca(self, ca_pem: Path, *, nickname: str = "Nullcell Local CA") -> str:
        """Import the local CA into *this profile only* (§8).

        Returns a human-readable outcome. Never touches the system trust store:
        §8 is explicit that doing so would be a real risk to the machine for
        everything else it does.
        """
        certutil = shutil.which("certutil")
        if certutil is None:
            return (
                "certutil no encontrado, así que la CA no se importó. "
                f"Instálalo (macOS: brew install nss) y ejecuta:\n"
                f"  certutil -A -n '{nickname}' -t C,, -i {ca_pem} -d sql:{self.directory}\n"
                "No instales esta CA en el almacén del sistema (§8)."
            )
        self.directory.mkdir(parents=True, exist_ok=True)
        command = [
            certutil,
            "-A",
            "-n",
            nickname,
            "-t",
            "C,,",
            "-i",
            str(ca_pem),
            "-d",
            f"sql:{self.directory}",
        ]
        try:
            result = subprocess.run(command, capture_output=True, text=True, timeout=30)
        except (OSError, subprocess.SubprocessError) as exc:
            return f"certutil falló: {exc}"
        if result.returncode != 0:
            return f"certutil devolvió {result.returncode}: {result.stderr.strip()}"
        return f"CA importada en el perfil como '{nickname}'"

    # ------------------------------------------------------------------ launch
    def launch_command(self, url: str, *, binary: Path | None = None) -> list[str] | None:
        firefox = binary or firefox_binary()
        if firefox is None:
            return None
        return [
            str(firefox),
            "-profile",
            str(self.directory),
            "-no-remote",  # do not join a running Firefox session
            "-new-instance",
            url,
        ]

    def launch(self, url: str, *, binary: Path | None = None) -> subprocess.Popen | None:
        command = self.launch_command(url, binary=binary)
        if command is None:
            return None
        log.info("launching %s", command[0])
        return subprocess.Popen(command, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
